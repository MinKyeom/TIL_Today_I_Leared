"""
해설 및 이해안된 결과 찾아본 결과

 expand(i, i + 1)과 expand(i, i + 2)는 비교하는 '중심점'과 '짝수/홀수 유형'이 완전히 다르기 때문에 중복 검사가 아닙니다.
 
 1. 왜 2칸(i, i+1)과 3칸(i, i+2) 두 번 호출할까?
 팰린드롬은 구조적으로 두 가지 형태가 존재합니다.짝수 길이 팰린드롬 (예: "abba")중심이 문자 사이에 있습니다.
 처음 비교를 i와 i + 1 두 문자가 같은지부터 시작해야 합니다.홀수 길이 팰린드롬 (예: "aba")중심이 특정 문자 하나입니다.자기 자신(i + 1)은 당연히 같으므로, 
 그 양옆인 i와 i + 2가 같은지부터 시작해야 합니다.즉, 이 두 호출은 같은 문자열을 반복해서 검사하는 게 아니라, "i 지점을 중심으로 하는 짝수 팰린드롬인가?"와 "i+1 지점을 중심으로 하는 홀수 팰린드롬인가?"라는 서로 다른 가능성을 각각 한 번씩 탐색하는 것입니다.
 2. 실제로 탐색하는 과정을 따라가 보면 (중복이 없는 이유)예를 들어 s = "ababa" 라는 문자열이 있고, i = 1 (문자 'b') 일 때를 살펴봅시다.
 expand(1, 2) 호출 (짝수 검사)s[1]('b') vs s[2]('a') 비교서로 다르므로 while문이 진행되지 않고 즉시 종료 $\rightarrow$ 비교 1번 수행expand(1, 3) 호출 (홀수 검사)s[1]('b') vs s[3]('b') 비교 $\rightarrow$ 같음! (확장)s[0]('a') vs s[4]('a') 비교 $\rightarrow$ 같음! (확장)더 이상 못 나가서 종료 $\rightarrow$ "ababa" 반환보시다시피, 짝수 검사는 시작하자마자 실패해서 끝나고, 홀수 검사만 쭉 확장해 나갑니다. 같은 짝을 여러 번 반복해서 비교하지 않습니다.
 3. 이 코드의 시간 복잡도가 손해가 아닌 이유for문은 문자열 전체를 한 번 훑습니다 ($N$번).매 위치에서 expand를 2번 부르지만, 시작점의 형태(짝수/홀수)가 다를 뿐 탐색 방향은 중심에서 밖으로 단 한 번씩만 나아갑니다.이미 팰린드롬이 아니라고 판정된 순간 while문이 바로 끝나므로, 무의미한 반복이 누적되지 않습니다.따라서 전체 비교 횟수는 최대 $O(N^2)$로 제한되며, 2중 for문으로 모든 부분 문자열을 잘라보는 방식($O(N^3)$)에 비하면 훨씬 효율적인 투 포인터 접근법입니다.


"""
class Solution:
    def longestPalindrome(self, s: str) -> str:
        # 팰린드롬 판별 및 투 포인터 확장
        # s[left] == s[right]: 이 팰린드롬인지 확인하는 조건.
        def expand(left: int, right: int) -> str:
            while left >= 0 and right < len(s) and s[left] == s[right]:
                left -= 1
                right += 1
            return s[left + 1:right] 
            # 입력받았던 포인터 기준으로 얻은 가장 큰 팰랜드롬 부분 문자열.
            # 하나 이전꺼 반환

        # 입력 문자열이 이미 팰린드롬이면 그 자체를 빠르게 반환.
        if len(s) < 2 or s == s[::-1]:
            return s

        result = ''
        # 슬라이딩 윈도우 우측으로 이동
        for i in range(len(s) - 1):
            result = max(result, # 한 칸 이전 포인터들까지의 가장 긴 팰린드롬 부분 문자열.
                         expand(i, i + 1), # 2칸짜리 포인터
                         expand(i, i + 2), # 3칸짜리 포인터
                         key=len) # 길이 기준으로
            
            print(result)
            
        return result
      
# max문법에서는 동률일때는 가장 처음 값이 선택된다

Test = Solution()

